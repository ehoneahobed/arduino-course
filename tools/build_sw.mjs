// Writes the offline file list, content hashes and version into sw.js (the part between its
// "generated" lines). Run it after changing, adding or removing any file of the site:
//
//   node tools/build_sw.mjs           update sw.js
//   node tools/build_sw.mjs --check   exit 1 if sw.js is out of date (changes nothing)
//
// The version is a hash of every file's content, so it only changes when something did, and
// browsers then fetch only the files whose hash changed. Plain Node, no packages needed.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const SW = ROOT + 'sw.js';

// Not for the offline copy: tools and sources, link-preview images, the server's own files.
const SKIP_DIR = /^(\.[^/]*|node_modules|tools|assets\/og|assets\/vendor|assets\/labs\/src)$/;
const SKIP_FILE = /(^|\/)(\.[^/]*|[^/]*\.md|LICENSE[^/]*|vercel\.json|sw\.js|robots\.txt|sitemap\.xml|404\.html|_[^/]*\.(tgz|zip))$/;

const walk = (dir) => readdirSync(ROOT + dir, { withFileTypes: true })
  .sort((a, b) => a.name.localeCompare(b.name))
  .flatMap((e) => {
    const rel = dir + e.name;
    if (e.isDirectory()) return SKIP_DIR.test(rel) ? [] : walk(rel + '/');
    return SKIP_FILE.test(rel) ? [] : [rel];
  });

// Same rule as keyOf() in sw.js: "arduino/bands/band-3.html" -> "arduino/bands/band-3", "index.html" -> "".
const keyOf = (rel) => rel.replace(/\.html$/, '').replace(/(^|\/)index$/, '$1').replace(/\/+$/, '');

const files = {};
let bytes = 0;
for (const rel of walk('')) {
  const data = readFileSync(ROOT + rel);
  bytes += data.length;
  files[keyOf(rel)] = createHash('sha256').update(data).digest('hex').slice(0, 12);
}

// Saved on the first visit: the pages a learner needs first, and everything every page loads.
const CORE_RE = /^(|offline|manifest\.webmanifest|arduino\/(home|profile)|arduino\/bands\/band-\d+|arduino-code\/(home|profile|modules\/list|modules\/module-00\/(home|01-what-is-a-microcontroller|02-arduino-ide-tour|03-tinkercad-lab-setup|04-anatomy-of-a-sketch|05-digital-write-and-blink|06-custom-blink-signature)|modules\/module-01\/(home|01-multiple-leds-and-variables|02-if-else-and-comparison|03-reading-a-button|04-contact-bounce|05-simple-software-debounce|06-for-and-while-loops|07-functions-that-do-one-job|08-crosswalk-quiz-buzzer)|modules\/module-02\/(home|01-why-delay-blocks|02-millis-heartbeat|03-several-timers-at-once|04-one-shot-and-repeating-timers|05-non-blocking-debounce|06-desk-status-light)|modules\/module-03\/(home|01-analog-vs-digital-pins|02-analog-read-and-serial|03-pwm-and-analog-write|04-threshold-logic|05-arrays-for-samples|06-auto-night-light)|modules\/module-04\/(home|01-when-to-use-a-library|02-ultrasonic-distance|03-temperature-sensor|04-servo-positioning|05-structs-for-sensor-packets|06-parking-assist-or-climate-alert)|modules\/module-05\/(home|01-spaghetti-vs-states|02-enum-and-switch-fsm|03-entry-exit-actions|04-events-vs-polling|05-modular-ino-organization|06-washing-machine-or-lock-fsm)|modules\/module-06\/(home|01-polling-limits|02-external-interrupts|03-volatile-and-shared-data|04-software-vs-hardware-debounce|05-i2c-display-hello-world|06-lap-counter-or-reaction-timer))|assets\/[^/]+\.(css|js)|assets\/labs\/labs\.(css|js)|assets\/fonts\/[^/]+\.woff2|assets\/brand\/(logo-mark-white|logo-mark|icon-192)\.png)$/;
const core = Object.keys(files).filter((k) => CORE_RE.test(k));

// vercel.json's redirects, so old addresses still work with no internet.
// "/bands/:path*" -> ["^bands(?:/(.*))?$", "arduino/bands/$1"]
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const vercel = JSON.parse(readFileSync(ROOT + 'vercel.json', 'utf8'));
const redirects = (vercel.redirects || []).map(({ source, destination }) => {
  const from = source.replace(/^\//, '');
  const re = from.endsWith('/:path*') ? `^${esc(from.slice(0, -7))}(?:/(.*))?$` : `^${esc(keyOf(from))}$`;
  return [re, destination.replace(/^\//, '').replace(':path*', '$1')];
}).filter((r, i, all) => all.findIndex((o) => o[0] === r[0]) === i); // "/guide" and "/guide.html" are one key

const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 12);
const block = [
  '// ---- generated by tools/build_sw.mjs: do not edit by hand ----',
  `const VERSION = '${version}';`,
  `const BYTES = ${bytes};`,
  `const REDIRECTS = ${JSON.stringify(redirects)};`,
  `const CORE = ${JSON.stringify(core, null, 1).replace(/\n /g, '\n  ')};`,
  `const FILES = {\n${Object.entries(files).map(([k, h]) => `  ${JSON.stringify(k)}: '${h}',`).join('\n')}\n};`,
  '// ---- end of generated part ----',
].join('\n');

const src = readFileSync(SW, 'utf8');
const out = src.replace(/\/\/ ---- generated by tools\/build_sw\.mjs[\s\S]*?\/\/ ---- end of generated part ----/, block);
if (out === src && !src.includes(block)) throw new Error('sw.js has no generated part to fill');
const mb = (bytes / 1048576).toFixed(1);
if (process.argv.includes('--check')) {
  console.log(out === src ? `sw.js is up to date (version ${version})` : 'sw.js is out of date: run node tools/build_sw.mjs');
  process.exit(out === src ? 0 : 1);
}
writeFileSync(SW, out);
console.log(`sw.js: version ${version}, ${Object.keys(files).length} files (${mb} MB), ${core.length} saved on the first visit`);
