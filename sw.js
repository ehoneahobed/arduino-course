async function ensure(cache, k) {
  if (isCurrent(await cache.match(at(k)), k)) return true;
  const old = await caches.match(at(k)); // an older version may hold the same content
  if (isCurrent(old, k)) { await cache.put(at(k), old); return true; }
  try {
    const res = await fetch(at(k), { cache: 'no-cache' });
    if (!res.ok) throw new Error(res.status);
    await store(cache, k, res);
    return true;
  } catch (e) {
    return false;
  }
}

// Files go one at a time (four side by side), so one failure on a weak connection doesn't undo the rest.
async function saveList(cache, keys, onEach) {
  let next = 0;
  let failed = 0;
  const worker = async () => {
    while (next < keys.length) {
      const k = keys[next++];
      if (!(await ensure(cache, k))) failed++;
      if (onEach) onEach(failed);
    }
  };
  await Promise.all([worker(), worker(), worker(), worker()]);
  return failed;
}

async function tellAll(msg) {
  for (const c of await self.clients.matchAll({ type: 'window', includeUncontrolled: true })) c.postMessage(msg);
}

// "Save the whole course": every file, with progress for every open page.
let saving = null;
async function saveAll() {
  if (saving) return saving.job;
  const cache = await caches.open(CACHE);
  const state = { done: 0, total: KEYS.length, failed: 0 };
  let last = 0;
  state.job = saveList(cache, KEYS, (failed) => {
    state.done++;
    state.failed = failed;
    const now = Date.now();
    if (now - last > 150 || state.done === state.total) {
      last = now;
      tellAll({ type: 'save-progress', done: state.done, total: state.total, failed });
    }
  }).then(async (failed) => {
    if (!failed) await cache.put(FULL_MARK, new Response(VERSION + ' ' + new Date().toISOString()));
    saving = null;
    await tellAll({ type: 'save-done', failed, total: state.total });
  });
  saving = state;
  return state.job;
}

// After an update: download again only what changed, and, if this device had saved
// the whole course, whatever is still missing. Runs once each time the worker wakes.
let toppedUp = false;
async function topUp() {
  if (toppedUp || saving) return;
  toppedUp = true;
  const cache = await caches.open(CACHE);
  const full = !!(await cache.match(FULL_MARK));
  if (full) return saveAll();
  const stale = [];
  for (const k of KEYS) {
    const have = await cache.match(at(k));
    if (have && !isCurrent(have, k)) stale.push(k);
  }
  if (stale.length) await saveList(cache, stale);
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    await saveList(await caches.open(CACHE), CORE);
    await self.skipWaiting();
  })());
});

// Messages can arrive while a new version is still moving the saved files across:
// they wait for that to finish.
let activated;
const activation = new Promise((resolve) => { activated = resolve; });
const me = self.serviceWorker || self.registration.active;
if (me && me.state === 'activated') activated(); // woken up again after it was set up
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    let wasFull = false;
    for (const name of await caches.keys()) {
      if (!name.startsWith(PREFIX) || name === CACHE) continue;
      const old = await caches.open(name);
      if (await old.match(FULL_MARK)) wasFull = true;
      // Carry over every saved file this version still uses, even if it changed:
      // an old copy is better than none until the fresh one arrives.
      for (const req of await old.keys()) {
        const k = keyOf(new URL(req.url).pathname);
        if (!(k in FILES) || (await cache.match(at(k)))) continue;
        await cache.put(at(k), await old.match(req));
      }
      await caches.delete(name);
    }
    if (wasFull) await cache.put(FULL_MARK, new Response(VERSION + ' carried over'));
    await self.clients.claim();
    activated();
    topUp(); // not awaited; open pages also ask for it, so it finishes even if this worker sleeps
  })());
});

self.addEventListener('message', (event) => {
  const m = event.data || {};
  const type = typeof m === 'string' ? m : m.type;
  if (type === 'save-all') event.waitUntil(activation.then(saveAll));
  else if (type === 'top-up') event.waitUntil(activation.then(topUp));
  else if (type === 'info') {
    event.waitUntil((async () => {
      await activation;
      const cache = await caches.open(CACHE);
      const full = !!(await cache.match(FULL_MARK));
      event.source && event.source.postMessage({
        type: 'info', version: VERSION, files: KEYS.length, bytes: BYTES, full,
        saving: saving ? { done: saving.done, total: saving.total } : null,
      });
    })());
  }
});

// With no internet: the old addresses of vercel.json still lead to their pages.
function redirected(k) {
  for (const [re, to] of REDIRECTS) {
    const m = k.match(new RegExp(re));
    if (m) return keyOf('/' + to.replace('$1', m[1] || ''));
  }
  return null;
}

async function offlineAnswer(request, k) {
  const hit = await caches.match(at(k));
  if (hit) return hit;
  const dest = redirected(k);
  if (dest !== null) {
    if (request.mode === 'navigate') return Response.redirect(at(dest) + new URL(request.url).search, 302);
    const moved = await caches.match(at(dest));
    if (moved) return moved;
  }
  if (request.mode === 'navigate') return caches.match(at('offline'));
  return undefined;
}

function keepCopy(event, k, res) {
  if (res.ok && res.type === 'basic' && !res.redirected) {
    const copy = res.clone();
    event.waitUntil(caches.open(CACHE).then((c) => store(c, k, copy)).catch(() => {}));
  }
  return res;
}

async function cacheFirst(event, k) {
  const hit = await caches.match(at(k));
  if (hit) return hit;
  try {
    return keepCopy(event, k, await fetch(event.request));
  } catch (e) {
    return (await offlineAnswer(event.request, k)) || Response.error();
  }
}

async function networkFirst(event, k) {
  const net = fetch(event.request).then((res) => keepCopy(event, k, res));
  net.catch(() => {}); // handled below
  const slow = new Promise((resolve) => setTimeout(resolve, TIMEOUT))
    .then(async () => (await caches.match(at(k))) || net);
  try {
    return await Promise.race([net, slow]);
  } catch (e) {
    return (await offlineAnswer(event.request, k)) || Response.error();
  }
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  const url = new URL(request.url);
  if (url.origin !== location.origin || !url.pathname.startsWith(SCOPE)) return; // YouTube and other sites: untouched
  const k = keyOf(url.pathname);
  if (k === 'sw.js' || k.startsWith('__')) return;
  event.respondWith(CACHE_FIRST.test(k) ? cacheFirst(event, k) : networkFirst(event, k));
});
